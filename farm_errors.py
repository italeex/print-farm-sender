def extract_log_error(text):
    for line in reversed((text or "").splitlines()):
        line = line.strip()
        if not line.startswith("!!"):
            continue
        try:
            payload = json.loads(line[2:].strip())
        except (ValueError, TypeError):
            continue
        code = str(payload.get("code") or "")
        match = re.search(r"(\d{3,4})", code)
        return (match.group(1) if match else code, str(payload.get("msg") or ""))
    return None


def _lookup(code):
    if code in CREALITY_ERRORS:
        return CREALITY_ERRORS[code]
    digit_match = re.search(r"(\d{3,4})", code or "")
    if digit_match and digit_match.group(1) in CREALITY_ERRORS:
        return CREALITY_ERRORS[digit_match.group(1)]
    return None


def _keyword_fallback(text):
    lowered = (text or "").lower()
    if "thermistor" in lowered:
        return ("Ошибка термистора", "Проверьте кабель термистора и разъёмы.")
    if "lost communication" in lowered or "mcu" in lowered:
        return ("Потеряна связь с MCU", "Проверьте кабели, питание платы и перезапустите принтер.")
    if "not heating" in lowered or "heater" in lowered:
        return ("Нагреватель не греет", "Проверьте нагреватель и термистор.")
    if "out of range" in lowered:
        return ("Перемещение вне диапазона", "Проверьте G-code и настройки слайсера.")
    if "filament" in lowered or "runout" in lowered:
        return ("Проблема с филаментом", "Проверьте заправку и датчик филамента.")
    if "endstop" in lowered or "probe" in lowered:
        return ("Проблема с датчиком", "Проверьте датчики и проводку.")
    if "timer too close" in lowered:
        return ("MCU не успевает", "Перезапустите принтер и выгрузите логи.")
    if "shutdown" in lowered:
        return ("Klipper остановлен", "Откройте Mainsail и проверьте состояние.")
    if "gcode" in lowered or "g-code" in lowered:
        return ("Ошибка G-code", "Проверьте файл и настройки слайсера.")
    return None


def parse_error(message="", *, state="", log_tail=""):
    message = (message or "").strip()
    state = (state or "").lower()
    log_tail = log_tail or ""
    if not message and state not in {"error", "shutdown"} and not log_tail:
        return None
    combined = message + "\n" + log_tail
    code = ""
    key_match = KEY_PATTERN.search(combined)
    if key_match:
        code = key_match.group(1)
    else:
        code_match = CODE_PATTERN.search(combined)
        if code_match:
            raw = code_match.group(1)
            code = raw.upper() if raw[:2].isalpha() else raw
        else:
            logged = extract_log_error(log_tail)
            if logged and logged[0]:
                code = logged[0]
    detail = ""
    for line in (message or "").splitlines():
        if line.strip():
            detail = line.strip()
            break
    if not detail:
        logged = extract_log_error(log_tail)
        if logged and logged[1]:
            detail = logged[1].strip()
    if not detail:
        detail = "Klipper сообщил об ошибке без текста"
    detail = detail[:300]
    if code:
        found = _lookup(code)
        if found:
            return ErrorInfo(code=code, label=found[0], hint=found[1], detail=detail)
        return ErrorInfo(
            code=code,
            label="Ошибка принтера",
            hint="Откройте Mainsail и проверьте состояние.",
            detail=detail,
        )
    if state == "shutdown" and not message:
        return ErrorInfo(
            code="",
            label="Klipper аварийно остановлен",
            hint="Откройте Mainsail и проверьте состояние.",
            detail=detail,
        )
    fallback = _keyword_fallback(combined)
    if fallback:
        return ErrorInfo(code="", label=fallback[0], hint=fallback[1], detail=detail)
    if state == "shutdown":
        return ErrorInfo(
            code="",
            label="Klipper аварийно остановлен",
            hint="Откройте Mainsail и проверьте состояние.",
            detail=detail,
        )
    return ErrorInfo(
        code="",
        label="Ошибка принтера",
        hint="Откройте Mainsail и проверьте состояние.",
        detail=detail,
    )
